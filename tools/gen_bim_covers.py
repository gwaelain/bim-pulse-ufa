# -*- coding: utf-8 -*-
"""Резюмируемый генератор обложек BIM Pulse через мост Reve. Живёт на 5.188.19.160.

Запускать раз в сутки (cron): лимит бесплатного Reve ~3-4 кадра в день на весь портфель,
одна генерация даёт два варианта. Готовые слоты пропускает, на первом пустом ответе
останавливается — пустой `files: []` означает «квота кончилась», а не «повезёт в следующий раз».

Очередь короткая и по приоритету: сначала внешние площадки и страницы услуг, статьи блога
живут на стоковых обложках — их 37, и они не продают.
"""
import json
import os
import time
import urllib.request

TOKEN = open("/opt/gpt-bridge/.token").read().strip()
OUT = "/opt/reve-bridge/bimpulse"
os.makedirs(OUT, exist_ok=True)

STYLE = ("Тёмный фон, глубокий синий и холодный голубой акцент, тонкие светящиеся линии, "
         "инженерная графика, чистый стиль технической иллюстрации, без текста и подписей, без людей, "
         "широкий формат 16:9")

SLOTS = [
    ("vc-ii-agent", "Стилизованный счёт-смета за ИИ-агента, разложенный по строкам расходов, рядом абстрактная фигура робота-помощника, тёплый оранжевый акцент на графах. " + STYLE),
    ("avtomatizaciya-proverki-modeley", "Каркасная 3D-модель здания, в которой несколько элементов подсвечены красным как найденные ошибки, рядом полупрозрачный чек-лист с галочками. " + STYLE),
    ("bim-avtomatizaciya-api", "Каркасная модель здания, от которой потоки данных расходятся к трём узлам: таблица, база данных, документ со сметой. " + STYLE),
    ("ii-v-proektirovanii", "Каркасная модель здания на экране и рядом светящаяся нейросетевая структура из узлов, соединённая с моделью тонкими линиями. " + STYLE),
    ("dynamo-scripts", "Визуальный граф из соединённых узлов-нод, ведущий к 3D-модели здания, узлы светятся, провода между ними как схема. " + STYLE),
    ("perevod-2d-v-bim", "Плоский чертёж плана здания слева поднимается и превращается в объёмную каркасную 3D-модель справа, переход показан светящимися линиями. " + STYLE),
    ("upravlenie-bim-proektami", "Каркасная модель здания, над которой полупрозрачная панель со статусами разделов и полосками готовности, как дашборд. " + STYLE),
    ("ii-bim-proektirovanie", "Восемь светящихся блоков, соединённых в цепочку вокруг каркасной модели здания, как карта системы. " + STYLE),
    ("test", "Шкала зрелости из четырёх сегментов, заполненная наполовину, рядом каркасная модель здания, ощущение проверки и измерения. " + STYLE),
    ("og-image", "Каркасная модель многоэтажного здания с пульсирующими светящимися линиями данных, ощущение живой системы, крупный план. " + STYLE),
]

log = open(OUT + "/gen.log", "a", encoding="utf-8")


def w(m):
    log.write(m + "\n"); log.flush()


w("=== RUN " + time.strftime("%Y-%m-%d %H:%M") + " ===")
made = 0
for name, prompt in SLOTS:
    if os.path.exists(f"{OUT}/{name}-1.webp"):
        continue
    try:
        req = urllib.request.Request(
            "http://localhost:8814/image",
            data=json.dumps({"prompt": prompt, "timeout": 220}).encode(),
            headers={"Authorization": "Bearer " + TOKEN, "Content-Type": "application/json"})
        r = json.load(urllib.request.urlopen(req, timeout=300))
        n = 0
        for i, f in enumerate(r.get("files", [])):
            img = urllib.request.urlopen("http://localhost:8814" + f, timeout=60).read()
            open(f"{OUT}/{name}-{i + 1}.webp", "wb").write(img); n += 1
        if n > 0:
            w(f"OK {name} {n}"); made += 1
        else:
            w(f"EMPTY {name} -> квота Reve, стоп"); break
    except Exception as e:  # noqa: BLE001
        w(f"ERR {name} {str(e)[:70]} -> стоп"); break
    if made >= 2:   # не выгребать всю дневную квоту у соседних проектов
        w("сделано 2 слота, остальное завтра"); break
w(f"итого за запуск: {made}")
